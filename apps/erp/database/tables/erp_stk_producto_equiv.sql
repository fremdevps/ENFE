comment on column erp_stk_producto_equiv.producto_id             is 'Producto (FK erp_stk_producto)';
comment on column erp_stk_producto_equiv.producto_id_equivalente is 'Producto que lo reemplaza (FK erp_stk_producto)';
comment on column erp_stk_producto_equiv.tipo                    is 'E=Equivalente (idéntico en uso), S=Sustituto (alternativa aceptable)';
comment on column erp_stk_producto_equiv.prioridad               is 'Orden en que se ofrece';
comment on column erp_stk_producto_equiv.observacion             is 'Observación';
comment on column erp_stk_producto_equiv.estado                  is 'A=Activo, I=Inactivo';
comment on column erp_stk_producto_equiv.creado_por              is 'Usuario que creó el registro (APP_USER o usuario de BD)';
comment on column erp_stk_producto_equiv.fecha_creacion          is 'Fecha y hora de creación (con zona horaria)';
comment on column erp_stk_producto_equiv.modificado_por          is 'Usuario de la última modificación (trigger _bu)';
