comment on column erp_gen_sucursal.direccion          is 'Dirección';
comment on column erp_gen_sucursal.numero_casa        is 'Número de casa (SIFEN dNumCas)';
comment on column erp_gen_sucursal.ubicacion_id       is 'Ciudad (FK erp_gen_ubicacion)';
comment on column erp_gen_sucursal.telefono           is 'Teléfono';
