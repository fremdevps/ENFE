-- =============================================================================
-- Tabla  : erp_gen_sucursal   (abrev: suc)
-- Sucursales / establecimientos de cada empresa (código de establecimiento SIFEN de 3 dígitos).
-- =============================================================================
create table erp_gen_sucursal (
    sucursal_id         number generated by default on null as identity,
    empresa_id          number         not null,
    codigo              varchar2(10)   not null,
    nombre              varchar2(100)  not null,
    establecimiento     varchar2(3)    not null,
    direccion           varchar2(400),
    numero_casa         varchar2(10),
    ubicacion_id        number,
    telefono            varchar2(30),
    email               varchar2(200),
    es_casa_matriz      varchar2(1)    default on null 'N' not null,
    estado              varchar2(1)    default on null 'A' not null,
    creado_por          varchar2(100)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
    fecha_creacion      timestamp with local time zone default on null systimestamp not null,
    modificado_por      varchar2(100),
    fecha_modificacion  timestamp with local time zone,
    constraint pk_erp_suc primary key (sucursal_id),
    constraint fk_erp_suc_emp foreign key (empresa_id) references adm_gen_empresa (empresa_id),
    constraint fk_erp_suc_ubi foreign key (ubicacion_id) references erp_gen_ubicacion (ubicacion_id),
    constraint uk_erp_suc_emp_codigo unique (empresa_id, codigo),
    constraint uk_erp_suc_emp_establec unique (empresa_id, establecimiento),
    constraint ck_erp_suc_codigo_mayus check (codigo = upper(codigo)),
    constraint ck_erp_suc_establecimiento check (regexp_like(establecimiento, '^[0-9]{3}$')),
    constraint ck_erp_suc_es_casa_matriz check (es_casa_matriz in ('S','N')),
    constraint ck_erp_suc_estado check (estado in ('A','I'))
);

-- (empresa_id ya indexado por la PK/UK)
create index idx_erp_suc_ubicacion_id on erp_gen_sucursal (ubicacion_id);

comment on table  erp_gen_sucursal is 'Sucursales / establecimientos de cada empresa (código de establecimiento SIFEN de 3 dígitos). Abrev: suc';
