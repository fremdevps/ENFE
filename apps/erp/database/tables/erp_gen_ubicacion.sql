-- =============================================================================
-- Tabla  : erp_gen_ubicacion   (abrev: ubi)
-- Ubicación geográfica jerárquica por país (departamento, distrito, ciudad) con código oficial.
-- =============================================================================
create table erp_gen_ubicacion (
    ubicacion_id        number generated by default on null as identity,
    pais_id             number         not null,
    ubicacion_id_padre  number,
    tipo                varchar2(3)    not null,
    codigo_oficial      varchar2(20)   not null,
    nombre              varchar2(150)  not null,
    estado              varchar2(1)    default on null 'A' not null,
    creado_por          varchar2(100)  default on null coalesce(sys_context('APEX$SESSION','APP_USER'), user) not null,
    fecha_creacion      timestamp with local time zone default on null systimestamp not null,
    modificado_por      varchar2(100),
    fecha_modificacion  timestamp with local time zone,
    constraint pk_erp_ubi primary key (ubicacion_id),
    constraint fk_erp_ubi_pai foreign key (pais_id) references erp_gen_pais (pais_id),
    constraint fk_erp_ubi_ubi_padre foreign key (ubicacion_id_padre) references erp_gen_ubicacion (ubicacion_id),
    constraint uk_erp_ubi_pais_tipo_codigo unique (pais_id, tipo, codigo_oficial),
    constraint ck_erp_ubi_tipo check (tipo in ('DEP','DIS','CIU')),
    constraint ck_erp_ubi_estado check (estado in ('A','I'))
);

-- (pais_id ya indexado por la PK/UK)
create index idx_erp_ubi_ubicacion_id_padre on erp_gen_ubicacion (ubicacion_id_padre);

