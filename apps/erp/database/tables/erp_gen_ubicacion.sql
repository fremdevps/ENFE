comment on column erp_gen_ubicacion.pais_id            is 'País (FK erp_gen_pais)';
comment on column erp_gen_ubicacion.ubicacion_id_padre is 'Ubicación superior (FK erp_gen_ubicacion); null = primer nivel';
comment on column erp_gen_ubicacion.tipo               is 'DEP=Departamento/estado, DIS=Distrito/municipio, CIU=Ciudad/localidad';
comment on column erp_gen_ubicacion.codigo_oficial     is 'Código oficial (tabla de SIFEN/DNIT para Paraguay)';
comment on column erp_gen_ubicacion.nombre             is 'Nombre';
comment on column erp_gen_ubicacion.estado             is 'A=Activo, I=Inactivo';
comment on column erp_gen_ubicacion.creado_por         is 'Usuario que creó el registro (APP_USER o usuario de BD)';
comment on column erp_gen_ubicacion.fecha_creacion     is 'Fecha y hora de creación (con zona horaria)';
comment on column erp_gen_ubicacion.modificado_por     is 'Usuario de la última modificación (trigger _bu)';
