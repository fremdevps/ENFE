comment on column erp_gen_empresa_func.empresa_id         is 'Empresa (FK adm_gen_empresa)';
comment on column erp_gen_empresa_func.funcionalidad_id   is 'Funcionalidad (FK erp_gen_funcionalidad)';
comment on column erp_gen_empresa_func.estado             is 'A=Activo, I=Inactivo';
comment on column erp_gen_empresa_func.creado_por         is 'Usuario que creó el registro (APP_USER o usuario de BD)';
comment on column erp_gen_empresa_func.fecha_creacion     is 'Fecha y hora de creación (con zona horaria)';
comment on column erp_gen_empresa_func.modificado_por     is 'Usuario de la última modificación (trigger _bu)';
comment on column erp_gen_empresa_func.fecha_modificacion is 'Fecha y hora de la última modificación (trigger _bu)';
